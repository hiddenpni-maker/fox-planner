import type { LanguageCode, TaskPriority } from '../types/planner';

const PERSIAN_DIGITS = ['۰', '۱', '۲', '۳', '۴', '۵', '۶', '۷', '۸', '۹'];

/** Converts ASCII digits into Persian digits when Persian UI is active. */
export function localizeDigits(value: string | number, lang: LanguageCode): string {
  const str = String(value);
  if (lang !== 'fa') return str;
  return str.replace(/\d/g, (d) => PERSIAN_DIGITS[Number(d)] ?? d);
}

/** Formats duration in minutes to a compact readable label. */
export function formatMinutesLabel(minutes: number, lang: LanguageCode): string {
  const safe = Math.max(0, Math.round(minutes));
  const hrs = Math.floor(safe / 60);
  const mins = safe % 60;
  if (lang === 'fa') {
    if (hrs === 0) return `${localizeDigits(mins, 'fa')} دقیقه`;
    if (mins === 0) return `${localizeDigits(hrs, 'fa')} ساعت`;
    return `${localizeDigits(hrs, 'fa')} ساعت و ${localizeDigits(mins, 'fa')} د`;
  }
  if (hrs === 0) return `${mins}m`;
  if (mins === 0) return `${hrs}h`;
  return `${hrs}h ${mins}m`;
}

export function getPriorityLabel(priority: TaskPriority, lang: LanguageCode): string {
  if (lang === 'fa') {
    if (priority === 'high') return 'فوری';
    if (priority === 'medium') return 'متوسط';
    return 'عادی';
  }
  if (priority === 'high') return 'High';
  if (priority === 'medium') return 'Medium';
  return 'Low';
}

